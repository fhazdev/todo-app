-- Sprout — baseline schema
--
-- Flyway owns this schema. EF Core maps to it and never migrates it; EF's own
-- migrations are switched off in Sprout.Infrastructure.DependencyInjection.
--
-- db/ef-model-snapshot.sql holds the DDL EF believes in, pinned by the
-- EfModelSnapshotTests test. This file must stay compatible with it. Where the two
-- deliberately differ, the difference is called out inline; every such case is SQL
-- expressing a rule EF cannot state, never a disagreement about shape.
